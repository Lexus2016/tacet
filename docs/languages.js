function updateSample() {
  sampleButtons.forEach(button => {
    button.setAttribute("aria-pressed", String(button.dataset.sample === activeSample));
  });
  sampleSteps.replaceChildren(...getSamples(picker.value)[activeSample].map(([labelKey, text, language]) => {
    const row = document.createElement("div");
    row.className = "sample-step";
    row.dataset.kind = labelKey;
    const label = document.createElement("dt");
    label.textContent = activeStrings[labelKey];
    const phrase = document.createElement("dd");
    phrase.lang = language;
    if (labelKey === "selectedText") {
      const marked = document.createElement("mark");
      marked.textContent = text;
      phrase.append(marked);
    } else {
      phrase.textContent = text;
    }
    row.append(label, phrase);
    return row;
  }));
}
